"""Markdown reports: one brief per designed opportunity, plus a leaderboard."""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path

from .models import Paper
from .prompts import DIMENSION_GUIDE


def write_brief(opp: dict, paper: Paper, output_dir: str) -> Path:
    brief = opp["brief"]
    folder = Path(output_dir) / f"{date.today():%Y-%m-%d}"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{opp['id']:04d}-{_slug(brief['product_name'])}.md"
    path.write_text(render_brief(opp, paper))
    return path


def render_brief(opp: dict, paper: Paper) -> str:
    b, ev = opp["brief"], opp["evaluation"]
    out = [
        f"# {b['product_name']}",
        "",
        f"**{b['one_liner']}**",
        "",
        f"Score {opp['composite']:.0f}/100 · verdict: {ev['verdict']} · evidence: {ev['evidence_level'].replace('_', ' ')} "
        f"· origin: {opp['origin']}",
        "",
        f"{ev['summary']}",
        "",
        "## Source",
        "",
        f"[{paper.title}]({paper.url})" if paper.url else paper.title,
        f"{paper.venue} · {paper.published}".strip(" ·"),
        "",
    ]
    if paper.extra.get("need_source"):
        title, url = paper.extra.get("need_source_title") or "the source study", paper.extra.get("need_source_url")
        out += ["**Unmet need found in:** " + (f"[{title}]({url})" if url else title), ""]
    if opp.get("idea_plan"):
        plan = opp["idea_plan"]
        out += ["## The breakthrough this idea needs", "",
                f"**Obstacle:** {plan['key_obstacle']}", "", f"**Why it is unsolved:** {plan['why_unsolved']}", "",
                f"**Recommended approach:** {plan['recommended_approach']}. {plan['why_recommended']}", "",
                "| Approach | Mechanism | First experiment | Cost and time |", "| --- | --- | --- | --- |"]
        out += [f"| {_cell(a['name'])} | {_cell(a['mechanism'])} | {_cell(a['first_experiment'])} | "
                f"{_cell(a['experiment_cost_and_time'])} |" for a in plan["approaches"]]
        out.append("")
    out += [
        "## Product",
        "",
        f"**Problem:** {b['problem']}",
        "",
        f"**Who benefits:** {b['who_benefits']}",
        "",
        f"**Breakthrough used:** {b['breakthrough_used']}",
        "",
        f"**How it works:** {b['how_it_works']}",
        "",
        "### Prototype parts",
        "",
        "| Component | Purpose | Off-the-shelf option |",
        "| --- | --- | --- |",
        *[f"| {_cell(c['component'])} | {_cell(c['purpose'])} | {_cell(c['off_the_shelf_option'])} |"
          for c in b["prototype_components"]],
        "",
        "### Build plan",
        "",
        "| Phase | Months | Goal | Est. cost | Exit criteria |",
        "| --- | --- | --- | --- | --- |",
        *[f"| {_cell(p['name'])} | {_cell(p['months'])} | {_cell(p['goal'])} | {_cell(p['estimated_cost_usd'])} | "
          f"{_cell(p['exit_criteria'])} |" for p in b["build_plan"]],
        "",
        "## Scores",
        "",
        "| Dimension | Score | Why |",
        "| --- | --- | --- |",
        *[f"| {dim.replace('_', ' ')} | {ev['scores'][dim]['score']}/10 | {_cell(ev['scores'][dim]['rationale'])} |"
          for dim in DIMENSION_GUIDE if dim in ev["scores"]],
        "",
        "## Competition",
        "",
        *([f"- **{c['name']}** ({c['stage']}): {c['what_they_do']}" + (f" [source]({c['source_url']})" if c["source_url"] else "")
           for c in ev["competitors"]] or ["- None found in the research."]),
        "",
        f"**Our edge:** {b['competitive_edge']}",
        "",
        "## Path to market",
        "",
        f"**Validation:** {b['validation_plan']}",
        "",
        f"**Regulatory:** {b['regulatory_path']}",
        "",
        f"**IP:** {b['ip_strategy']}",
        "",
        f"**Business model:** {b['business_model']}",
        "",
        "**Funding sources:**",
        *[f"- {f}" for f in b["funding_sources"]],
        "",
        "**Team needed:**",
        *[f"- {t}" for t in b["team_needed"]],
        "",
        "## Risks",
        "",
        *[f"- **{r['risk']}** Mitigation: {r['mitigation']}" for r in b["risks"]],
        "",
        "**Kill criteria:**",
        *[f"- {k}" for k in b["kill_criteria"]],
        "",
        "## First 90 days",
        "",
        *[f"{i}. {step}" for i, step in enumerate(b["first_90_days"], 1)],
        "",
        "## Research sources",
        "",
        *([f"- [{s['title']}]({s['url']})" for s in opp.get("landscape_sources") or []] or ["- None recorded."]),
        "",
        "_Generated by the Breakthrough Engine. Scores and estimates are model judgments from web research; "
        "verify key facts before acting._",
        "",
    ]
    return "\n".join(out)


def leaderboard(opps: list[dict], papers: dict[str, Paper], owned: list[tuple[Paper, dict]] = ()) -> str:
    rows = ["| # | Score | Verdict | Opportunity | Origin | Status | Brief |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for opp in opps:
        if opp["composite"] is None:
            continue
        paper = papers.get(opp["paper_key"])
        name = (opp.get("brief") or {}).get("product_name") or (paper.title if paper else "?")
        brief = f"[open]({opp['report_path']})" if opp.get("report_path") else ""
        rows.append(f"| {opp['id']} | {opp['composite']:.0f} | {opp['verdict']} | {_cell(name)} | {opp['origin']} | "
                    f"{opp['status']} | {brief} |")
    out = ["# Opportunity leaderboard", "", *rows, ""]
    if owned:
        out += ["## Already owned", "", "Screened out before judging because someone already owns the product.", "",
                "| Research | Owner | Evidence | Adjacent product |", "| --- | --- | --- | --- |"]
        out += [f"| {_link(p)} | {_cell(c['owner'])} | {_cell(c['evidence'])} | {_cell(c['wedge'])} |" for p, c in owned]
        out.append("")
    return "\n".join(out)


def _link(paper: Paper | None) -> str:
    if paper is None:
        return "?"
    return f"[{_cell(paper.title)}]({paper.url})" if paper.url else _cell(paper.title)


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "/")


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:50] or "brief"
